  let currentPref = "auto";
  let currentLang = "zh";

  function normalizePref(pref) {
    const p = String(pref || "").trim().toLowerCase();
    if (p === "zh" || p === "zh-cn" || p === "zh-hans") return "zh";
    if (p === "en" || p === "en-us" || p === "en-gb") return "en";
    return "auto";
  }

  function detectSystemLang() {
    try {
      const navLang = String(
        (navigator.languages && navigator.languages[0]) ||
        navigator.language ||
        navigator.userLanguage ||
        "zh-CN"
      ).toLowerCase();
      return navLang.startsWith("zh") ? "zh" : "en";
    } catch (_) {
      return "zh";
    }
  }

  function resolveLang(pref) {
    const norm = normalizePref(pref);
    return norm === "auto" ? detectSystemLang() : norm;
  }

  function t(key, vars) {
    const table = STRINGS[currentLang] || STRINGS.zh;
    let out = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : (Object.prototype.hasOwnProperty.call(STRINGS.zh, key) ? STRINGS.zh[key] : key);
    if (vars && typeof vars === "object") {
      out = String(out).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) =>
        vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ""
      );
    }
    return String(out);
  }

  function applyDom(root) {
    const scope = root || document;
    if (!scope || !scope.querySelectorAll) return;

    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (key) el.innerHTML = t(key);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", t(key));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    scope.querySelectorAll("[data-i18n-prompt]").forEach((el) => {
      const key = el.getAttribute("data-i18n-prompt");
      if (key) el.setAttribute("data-prompt", t(key));
    });

    if (!root || root === document) {
      document.title = t("doc.title");
      document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
      document.documentElement.dataset.lang = currentLang;
    }
  }

  function setLang(pref, opts = {}) {
    const norm = normalizePref(pref);
    currentPref = norm;
    currentLang = resolveLang(norm);
    if (opts.persistFast !== false) {
      try {
        localStorage.setItem(LANG_STORAGE_KEY, norm);
      } catch (_) {}
    }
    if (opts.applyDom !== false) {
      applyDom(document);
    }
    return currentLang;
  }

  function fmtTokens(n) {
    const v = Number(n) || 0;
    if (currentLang === "en") {
      if (v >= 1e9) return `${(v / 1e9).toFixed(2)}B`;
      if (v >= 1e6) return `${(v / 1e6).toFixed(2)}M`;
      if (v >= 1e3) return `${(v / 1e3).toFixed(1)}K`;
      return String(Math.round(v));
    }
    if (v >= 1e8) return `${(v / 1e8).toFixed(2)} 亿`;
    if (v >= 1e4) return `${(v / 1e4).toFixed(1)} 万`;
    if (v >= 1e3) return `${(v / 1e3).toFixed(1)}K`;
    return String(Math.round(v));
  }

  function fmtResetLeft(days, remH, hrs) {
    if (currentLang === "en") {
      return days > 0 ? `in ${days}d ${remH}h` : `in ${Math.max(1, hrs)}h`;
    }
    return days > 0 ? `${days}天${remH}时后` : `${Math.max(1, hrs)}小时后`;
  }

  function readSavedFastPref() {
    try {
      const saved = localStorage.getItem(LANG_STORAGE_KEY);
      if (saved) return normalizePref(saved);
    } catch (_) {}
    return "auto";
  }

  // Initialize synchronously from fast storage or system locale before first paint
  currentPref = readSavedFastPref();
  currentLang = resolveLang(currentPref);
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.lang = currentLang;

